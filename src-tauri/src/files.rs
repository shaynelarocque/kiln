use serde::Deserialize;
use std::collections::HashSet;
use std::fs;
use std::io::Read;
use std::path::{Component, Path, PathBuf};

/// Every file Kiln regenerates starts with this, which is how stale ones are recognised.
const GENERATED: &[u8] = b"/* Generated by Kiln";

#[tauri::command]
pub fn read_text(path: String) -> Result<String, String> {
    fs::read_to_string(&path)
        .map_err(|e| format!("{path}: {e}"))
        .inspect_err(|e| log::warn!("couldn't read {e}"))
}

/// Saves through a temp file and a rename, so a crash mid-write can't truncate a project.
#[tauri::command]
pub fn write_text(path: String, contents: String) -> Result<(), String> {
    let tmp = format!("{path}.tmp");
    fs::write(&tmp, contents)
        .and_then(|_| fs::rename(&tmp, &path))
        .map_err(|e| format!("{path}: {e}"))
        .inspect_err(|e| log::warn!("couldn't save {e}"))
}

#[derive(Deserialize)]
pub struct OutFile {
    path: String,
    content: String,
    /// false: only written if missing (the user's own code lives there)
    overwrite: bool,
    /// also written over an existing file that starts with this: one an older Kiln generated
    #[serde(default)]
    replaces: Option<String>,
}

/// Plain relative paths only: an export can't escape the folder it was given.
fn inside(root: &Path, rel: &str) -> Result<PathBuf, String> {
    let rel_path = Path::new(rel);
    if rel_path.is_absolute() || !rel_path.components().all(|c| matches!(c, Component::Normal(_))) {
        return Err(format!("refusing to write outside the export folder: {rel}"));
    }
    Ok(root.join(rel_path))
}

/// Deletes files in `src/ui` that an earlier export generated but this one doesn't (a renamed or
/// deleted screen's file would otherwise still be compiled, and break the link). Only files that
/// start with Kiln's header go; anything you put there yourself stays.
fn remove_stale(root: &Path, keep: &HashSet<String>) -> Result<(), String> {
    let ui = root.join("src/ui");
    let Ok(entries) = fs::read_dir(&ui) else { return Ok(()) };
    for entry in entries.flatten() {
        let path = entry.path();
        let rel = format!("src/ui/{}", entry.file_name().to_string_lossy());
        if !path.is_file() || keep.contains(&rel) {
            continue;
        }
        let mut head = [0u8; 20];
        let generated = fs::File::open(&path).and_then(|mut f| f.read_exact(&mut head)).is_ok() && head == GENERATED;
        if generated {
            fs::remove_file(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        }
    }
    Ok(())
}

/// Writes an exported PlatformIO project and returns the paths it wrote.
#[tauri::command]
pub fn write_project(dir: String, files: Vec<OutFile>) -> Result<Vec<String>, String> {
    export(&dir, files)
        .inspect(|written| log::info!("exported {} files to {dir}", written.len()))
        .inspect_err(|e| log::warn!("export to {dir} failed: {e}"))
}

fn export(dir: &str, files: Vec<OutFile>) -> Result<Vec<String>, String> {
    let root = PathBuf::from(dir);
    let keep: HashSet<String> = files.iter().map(|f| f.path.clone()).collect();
    remove_stale(&root, &keep)?;
    let mut written = Vec::new();
    for file in files {
        let target = inside(&root, &file.path)?;
        let outdated = |prefix: &String| {
            fs::read_to_string(&target).is_ok_and(|old| old.starts_with(prefix.as_str()))
        };
        if !file.overwrite && target.exists() && !file.replaces.as_ref().is_some_and(outdated) {
            continue;
        }
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        fs::write(&target, file.content).map_err(|e| format!("{}: {e}", target.display()))?;
        written.push(file.path);
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_paths_that_leave_the_folder() {
        let root = Path::new("/tmp/out");
        assert!(inside(root, "src/ui/ui.c").is_ok());
        assert!(inside(root, "../evil").is_err());
        assert!(inside(root, "/etc/passwd").is_err());
        assert!(inside(root, "src/../../x").is_err());
    }

    #[test]
    fn removes_only_stale_generated_files() {
        let dir = std::env::temp_dir().join(format!("kiln-stale-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("src/ui")).unwrap();
        fs::write(dir.join("src/ui/ui_old.c"), "/* Generated by Kiln from \"x\" */").unwrap();
        fs::write(dir.join("src/ui/mine.c"), "// my own helper").unwrap();
        let file = |p: &str| OutFile { path: p.into(), content: "/* Generated by Kiln */".into(), overwrite: true, replaces: None };
        write_project(dir.to_string_lossy().into(), vec![file("src/ui/ui.c"), file("src/ui/ui_new.c")]).unwrap();
        assert!(!dir.join("src/ui/ui_old.c").exists());
        assert!(dir.join("src/ui/mine.c").exists());
        assert!(dir.join("src/ui/ui_new.c").exists());
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn keeps_files_marked_not_to_overwrite() {
        let dir = std::env::temp_dir().join(format!("kiln-test-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let d = dir.to_string_lossy().to_string();
        let file = |c: &str, overwrite| OutFile { path: "src/app.cpp".into(), content: c.into(), overwrite, replaces: None };
        assert_eq!(write_project(d.clone(), vec![file("first", false)]).unwrap(), vec!["src/app.cpp"]);
        assert!(write_project(d.clone(), vec![file("second", false)]).unwrap().is_empty());
        assert_eq!(fs::read_to_string(dir.join("src/app.cpp")).unwrap(), "first");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn upgrades_a_file_an_older_kiln_wrote_but_keeps_yours() {
        let dir = std::env::temp_dir().join(format!("kiln-ini-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let d = dir.to_string_lossy().to_string();
        let ini = |c: &str| OutFile {
            path: "platformio.ini".into(),
            content: c.into(),
            overwrite: false,
            replaces: Some("; Generated by Kiln for".into()),
        };
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("platformio.ini"), "; Generated by Kiln for \"x\". Regenerated on export").unwrap();
        write_project(d.clone(), vec![ini("; yours now")]).unwrap();
        assert_eq!(fs::read_to_string(dir.join("platformio.ini")).unwrap(), "; yours now");
        // once it's yours, your edits stay
        fs::write(dir.join("platformio.ini"), "; yours now\n-D ARDUINO_USB_CDC_ON_BOOT=1").unwrap();
        write_project(d.clone(), vec![ini("; yours now")]).unwrap();
        assert!(fs::read_to_string(dir.join("platformio.ini")).unwrap().contains("CDC_ON_BOOT"));
        let _ = fs::remove_dir_all(&dir);
    }
}

const HEADER = (project: Project) =>
  `/* Generated by Kiln from "${cComment(project.name)}" (LVGL ${LVGL_VERSION}). Regenerated on every export: edit app.cpp, not this. */`

/*
 * Project files can come from anywhere, and these files are compiled (and platformio.ini is run by
 * pio on this machine): numbers are forced finite, colours must be #rrggbb, ids must look like ids.
 */
const HEX = /^#[0-9a-f]{6}$/i
const num = (v: unknown) => (Number.isFinite(Number(v)) ? Math.trunc(Number(v)) : 0)
const pin = (v: unknown) => Math.max(-1, num(v))
const color = (v: string, fallback: string) => (HEX.test(v) ? v : fallback)
/** PlatformIO board ids are plain identifiers; anything else could inject ini sections. */
export const BOARD_ID = /^[\w.-]+$/
const iniText = (text: string) => text.replace(/[\x00-\x1f\x7f]/g, " ")

const indent = (lines: string[], by = "    ") => lines.map(l => (l ? by + l : l))

/** C statements for a block of ops, with a blank line before each new widget. */
function statements(ops: Op[], names: Record<string, string>) {
  const out: string[] = []
  for (const op of ops) {
    if (op.op === "create" && out.length) out.push("")
    out.push(...opToC(op, names))
  }
  return out
}

/** Every built-in font the UI uses, plus the default the theme needs and the imported fonts' fallbacks. */
export function usedFonts(project: Project) {
  const fonts = new Set([DEFAULT_FONT])
  const add = (v: unknown) => typeof v === "string" && v.startsWith("lv_font_") && fonts.add(v)
  for (const n of allNodes(project))
    for (const props of Object.values(n.style)) add(props.text_font)
  for (const s of project.styles) add(s.props.text_font)
  // worked out on the screens as the export builds them, like compile does
  for (const f of ttfFallbacks({ ...project, screens: resolveScreens(project, false) }).values())
    fonts.add(f)
  return [...fonts].sort()
}

/** The imported fonts' file sizes and the TinyTTF font sizes made from them. */
function ttfBudget(project: Project) {
  const uses = ttfUses(project)
  const files = project.fonts.filter(f => uses.some(u => u.id === f.id))
  return {
    ttfBytes: files.reduce((sum, f) => sum + Math.ceil((f.data.length * 3) / 4), 0),
    ttfSizes: uses.map(u => u.size),
  }
}

/** Laid-out widget sizes by node id, as the editor's preview measured them. */
export type Boxes = Map<string, { w: number; h: number }>

/**
 * The widget whose rotation or scale needs the biggest layer on the board, and its bytes.
 * Sizes come from `boxes`; without them, numeric layout sizes, or the whole display.
 */
export function largestLayer(project: Project, boxes?: Boxes) {
  const { width, height, bufferRows } = project.target.display
  /** A content-sized node's box without the preview: a label from its text, an image from its source. */
  const guess = (n: Node) => {
    const zoom = num(n.props.scale) || 256
    const source =
      n.widget === "image"
        ? project.assets.find(a => a.id === n.props.src)
        : project.sprites.find(s => s.id === n.props.sprite)
    if (source) return { w: (num(source.width) * zoom) / 256, h: (num(source.height) * zoom) / 256 }
    if (n.widget === "label") {
      const font = String(n.style["main:default"]?.text_font ?? DEFAULT_FONT)
      const px = Number(/(\d+)$/.exec(font)?.[1] ?? 14)
      const lines = String(n.props.text ?? "").split("\n")
      return { w: Math.max(...lines.map(l => l.length)) * px * 0.6, h: lines.length * px * 1.2 }
    }
    return { w: width, h: height }
  }
  let best: { name: string; bytes: number } | null = null
  for (const [id, t] of transformedNodes(project)) {
    const { w, h } = t.node.layout
    const box = boxes?.get(id) ?? {
      w: typeof w === "number" ? w : Math.min(width, Math.ceil(guess(t.node).w)),
      h: typeof h === "number" ? h : Math.min(height, Math.ceil(guess(t.node).h)),
    }
    const bytes = transformLayerBytes(box.w, box.h, t, num(bufferRows))
    if (!best || bytes > best.bytes) best = { name: t.node.name, bytes }
  }
  return best
}

export function budgetFor(project: Project, board: Board | undefined, boxes?: Boxes) {
  const layer = largestLayer(project, boxes)
  const nodes = allNodes(project)
  const strings = nodes.reduce(
    (sum, n) =>
      sum +
      Object.values(n.props)
        .filter(v => typeof v === "string")
        .join("").length,
    0,
  )
  const budget = estimateBudget({
    ram: board?.ram ?? 320 * 1024,
    rom: appPartition(board?.platform ?? "espressif32", board?.rom ?? 4 * 1024 * 1024),
    width: project.target.display.width,
    height: project.target.display.height,
    bufferRows: project.target.display.bufferRows,
    objects: nodes.length,
    styleProps: nodes.reduce(
      (sum, n) => sum + Object.values(n.style).reduce((s, p) => s + Object.keys(p).length, 0),
      0,
    ),
    stringBytes: strings + project.variables.filter(v => v.type === "string").length * 128,
    fonts: usedFonts(project),
    ...ttfBudget(project),
    imageBytes:
      project.assets.reduce((sum, a) => sum + Math.ceil((a.data.length * 3) / 4), 0) +
      // only sprites a widget plays are compiled in
      project.sprites
        .filter(s => nodes.some(n => n.widget === "sprite" && n.props.sprite === s.id))
        .reduce(
          (sum, s) => sum + s.frames.reduce((f, fr) => f + Math.ceil((fr.data.length * 3) / 4), 0),
          0,
        ),
    widgetTypes: new Set(nodes.map(n => n.widget)).size,
    layerBytes: layer?.bytes ?? 0,
  })
  return { ...budget, layer }
}

function uiFiles(project: Project): FirmwareFile[] {
  const program = compile(project, "export")
  if (!program.screens.length)
    throw new Error("There's no screen to export (the Components screen doesn't count)")
  const { names } = program
  const head = HEADER(project)
  const screenNames = program.screens.map(s => names[s.id])
  const setupDecls = declarations(program.setup, names)
  const wiringDecls = declarations(program.wiring, names)
  const screenDecls = program.screens.map(s => declarations(s.ops, names))
  const theme = project.theme

  const externs = (kind: string, type: string) =>
    [...setupDecls, ...wiringDecls, ...screenDecls.flat()]
      .filter(d => d.kind === kind)
      .map(d => `extern ${type} ${d.name};`)

  const tokenLines = project.tokens
    .filter(t => HEX.test(t.value))
    .map(t => `#define ${names[t.id]} 0x${t.value.slice(1).toUpperCase()}`)
  const variableDocs = project.variables.map(v => {
    const range = v.type === "int" ? ` (${num(v.min)}..${num(v.max)})` : ""
    return `extern lv_subject_t * ${names[v.id]}; /* ${cComment(v.name)}: ${v.type === "int" ? "int" : "string"}${range} */`
  })

  const uiH = [
    head,
    "#ifndef UI_H",
    "#define UI_H",
    "",
    "#ifdef __cplusplus",
    'extern "C" {',
    "#endif",
    "",
    '#include "lvgl.h"',
    "",
    ...(tokenLines.length ? ["/* Colour tokens */", ...tokenLines, ""] : []),
    ...(variableDocs.length
      ? [
          "/* Variables. Read with lv_subject_get_int(ui_var_x), set with lv_subject_set_int(ui_var_x, v):",
          " * every bound widget follows. */",
          ...variableDocs,
          "",
        ]
      : []),
    "/* Screens and widgets */",
    ...externs("obj", "lv_obj_t *"),
    "",
    ...[
      ...externs("style", "lv_style_t"),
      ...externs("timeline", "lv_anim_timeline_t *"),
      ...externs("series", "lv_chart_series_t *"),
      ...externs("transition", "lv_style_transition_dsc_t"),
      ...externs("image", "const lv_image_dsc_t"),
      ...externs("font", "const lv_font_t *"),
      // sized, so ui.c can take sizeof() for TinyTTF
      ...program.setup.flatMap(op =>
        op.op === "frames" ? [`extern const void * ${names[op.id]}[${op.images.length}];`] : [],
      ),
      ...program.setup.flatMap(op =>
        op.op === "ttf" ? [`extern const uint8_t ${names[op.id]}[${op.data.length}];`] : [],
      ),
    ],
    "",
    "/** Builds every screen and loads the first. Call once, after the display is set up. */",
    "void ui_init(void);",
    ...program.screens.map(s => `void ${names[s.id]}_create(void);`),
    "",
    "#ifdef __cplusplus",
    '} /*extern "C"*/',
    "#endif",
    "",
    "#endif /*UI_H*/",
    "",
  ].join("\n")

  const setupOps = program.setup.filter(op => op.op !== "image" && op.op !== "ttf")
  const uiC = [
    head,
    '#include "ui.h"',
    '#include "kiln_helpers.h"',
    "",
    ...setupDecls.filter(d => d.kind !== "image" && d.kind !== "ttf").map(d => d.c),
    ...wiringDecls.map(d => d.c),
    "",
    "/* Variables, shared styles and transitions: everything screens refer to. */",
    "static void ui_setup(void)",
    "{",
    ...indent(statements(setupOps, names)),
    "}",
    "",
    "/* Animations and interactions: these refer across screens, so they come last. */",
    "static void ui_wire(void)",
    "{",
    ...(usesAnim(program.wiring) ? ["    lv_anim_t a;", ""] : []),
    ...indent(statements(program.wiring, names)),
    "}",
    "",
    "void ui_init(void)",
    "{",
    "    lv_display_t * display = lv_display_get_default();",
    `    lv_theme_t * theme = lv_theme_default_init(display, ${cColor(color(theme.primary, "#2196f3"))}, ${cColor(color(theme.secondary, "#ff5722"))}, ${Boolean(theme.dark)}, LV_FONT_DEFAULT);`,
    "    lv_display_set_theme(display, theme);",
    "",
    "    ui_setup();",
    ...screenNames.map(n => `    ${n}_create();`),
    "    ui_wire();",
    `    lv_screen_load(${screenNames[0]});`,
    "}",
    "",
  ].join("\n")

  const screens: FirmwareFile[] = program.screens.map((s, i) => ({
    path: `src/ui/${screenNames[i]}.c`,
    overwrite: true,
    content: [
      head,
      '#include "ui.h"',
      '#include "kiln_helpers.h"',
      "",
      ...screenDecls[i].map(d => d.c),
      "",
      `void ${screenNames[i]}_create(void)`,
      "{",
      ...indent(statements(s.ops, names)),
      "}",
      "",
    ].join("\n"),
  }))

  const images = setupDecls.filter(d => d.kind === "image")
  const ttfs = setupDecls.filter(d => d.kind === "ttf")
  return [
    { path: "src/ui/ui.h", content: uiH, overwrite: true },
    { path: "src/ui/ui.c", content: uiC, overwrite: true },
    ...screens,
    ...(images.length
      ? [
          {
            path: "src/ui/ui_images.c",
            overwrite: true,
            content: [head, '#include "ui.h"', "", ...images.map(d => d.c + "\n")].join("\n"),
          },
        ]
      : []),
    ...(ttfs.length
      ? [
          {
            path: "src/ui/ui_fonts.c",
            overwrite: true,
            content: [head, '#include "ui.h"', "", ...ttfs.map(d => d.c + "\n")].join("\n"),
          },
        ]
      : []),
    { path: "src/ui/kiln_helpers.h", content: helpersH, overwrite: true },
    { path: "src/ui/kiln_helpers.c", content: helpersC, overwrite: true },
  ]
}


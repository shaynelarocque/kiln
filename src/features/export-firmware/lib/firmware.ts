function platformioIni(project: Project, board: Board | undefined) {
  const env = project.target.board
  if (!BOARD_ID.test(env)) throw new Error(`"${env}" isn't a PlatformIO board id`)
  const platform = board && BOARD_ID.test(board.platform) ? board.platform : "espressif32"
  return [
    `; Generated by Kiln for "${iniText(project.name)}". Regenerated on export; your code goes in src/app.cpp.`,
    "",
    "[platformio]",
    `default_envs = ${env}`,
    "",
    `[env:${env}]`,
    `platform = ${platform}`,
    `board = ${env}`,
    "framework = arduino",
    "monitor_speed = 115200",
    "lib_deps =",
    `    lvgl/lvgl@${LVGL_VERSION}`,
    "    lovyan03/LovyanGFX@^1.2.7",
    "build_flags =",
    "    -D LV_CONF_INCLUDE_SIMPLE",
    "    -I include",
    "    -O2",
    "; Boards that print over native USB (ESP32-C3 SuperMini, XIAO) also want:",
    ";   -D ARDUINO_USB_CDC_ON_BOOT=1",
    "",
  ].join("\n")
}

/** The whole PlatformIO project for the current target. */
export function generateFirmware(project: Project, board: Board | undefined): FirmwareFile[] {
  return [
    { path: "platformio.ini", content: platformioIni(project, board), overwrite: true },
    { path: "include/lv_conf.h", content: lvConf(project, board), overwrite: true },
    { path: "include/lgfx_user.hpp", content: lgfxUser(project, board), overwrite: true },
    { path: "src/main.cpp", content: mainCpp(project), overwrite: true },
    ...hardware(project),
    ...uiFiles(project),
    { path: "src/app.cpp", content: APP_CPP, overwrite: false },
    { path: ".gitignore", content: ".pio\n", overwrite: false },
  ]
}

